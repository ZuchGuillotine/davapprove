const assert = require('node:assert/strict');
const { JSDOM } = require('../web/node_modules/jsdom');
const Exports = require('../bid-assistant/lib/exports.js');
const Geo = require('../bid-assistant/lib/geo.js');
const Screen = require('../bid-assistant/lib/screen.js');
const parcel = Screen.buildParcel([{ geometry: { rings: [[[-122.65,47.6],[-122.649,47.6],[-122.649,47.601],[-122.65,47.601],[-122.65,47.6]]] } }], { parcel_key: 'test' });
const grid = Geo.gridAnalyze(parcel.shape, [], { targetSamples: 100 });
const screening = { screened_at: '2026-11-16T12:00:00Z', layers: {} };
const svg = Exports.mapSvg(parcel, grid, screening, { agency: 'Coates Design', title: 'Site assessment', incomplete: true });
const doc = new JSDOM(svg, { contentType: 'image/svg+xml' }).window.document;
assert.equal(doc.documentElement.getAttribute('viewBox'), '0 0 1000 750');
assert.match(doc.documentElement.textContent, /Coates Design/);
assert.match(doc.documentElement.textContent, /Coverage incomplete/);
assert.match(doc.documentElement.textContent, /Unresolved area/);
assert.match(doc.documentElement.textContent, /Approx\./);
assert.match(doc.documentElement.textContent, /Prepared with Davapprove/);
assert(!doc.querySelector('image'), 'export has no async basemap dependency');
const outline = doc.querySelector('clipPath#map-parcel path').getAttribute('d');
const coordinates = [...outline.matchAll(/[ML]([\d.]+),([\d.]+)/g)].map(m=>[Number(m[1]),Number(m[2])]);
assert(coordinates.every(([x,y])=>x>30 && x<970 && y>110 && y<590), 'entire parcel fits export viewport with context');
assert(Math.max(...coordinates.map(p=>p[1]))-Math.min(...coordinates.map(p=>p[1])) > 300, 'parcel is visible at parcel scale');
assert.equal(Exports.mapSvg(parcel, grid, screening, {agency:'Coates Design',title:'Site assessment',incomplete:true,zoom:1,pan:[999,999]}), svg, 'user viewport does not affect export');
assert.equal(Exports.mapSvg(null, grid, screening), '');
const unsafe = Exports.mapSvg(parcel, grid, screening, {agency:'<script>alert(1)</script>',title:'<img src=x onerror=alert(1)>',incomplete:true});
const unsafeDoc = new JSDOM(unsafe,{contentType:'image/svg+xml'}).window.document;
assert(!unsafeDoc.querySelector('script,img'), 'user branding is rendered as text');
assert.match(unsafeDoc.documentElement.textContent, /<script>/);
assert.equal(Exports.agencyName('  Acme\nDesign\tLLC '), 'Acme Design LLC');
assert.equal(Exports.agencyName({name:'Do not stringify'}), '');
assert.equal(Exports.agencyName('a'.repeat(200)).length,160);
console.log('PASS: bid exports (agency branding, fixed parcel extent, coverage labels, scale, offline SVG and escaping).');
