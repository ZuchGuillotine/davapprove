const assert = require('node:assert/strict');
const Drafts = require('../bid-assistant/lib/drafts.js');
const Screen = require('../bid-assistant/lib/screen.js');
const Geo = require('../bid-assistant/lib/geo.js');
const values = new Map();
const storage = { getItem: k => values.get(k) || null, setItem: (k,v) => values.set(k,v) };
const geometry = { rings: [[[-122.65,47.6],[-122.649,47.6],[-122.649,47.601],[-122.65,47.601],[-122.65,47.6]]] };
const parcel = Screen.buildParcel([{geometry}], {parcel_key:'test-parcel',rp_acct_id:123});
const state = { pack: {id:'wa-kitsap'}, parcel, draftId:'first', facts:{parcel:{situs:'SYNTHETIC BID'}},
  screening:{screened_at:'2026-11-13T00:00:00Z', layers:{wetland:{status:'unknown',error:'Timeout',features:[]}},tables:{permits:{rows:[{PERMIT_NO:'sample',PROJECT_NAME:'PRIVATE',APPLICANT:'PRIVATE',OWNER_AGENT_NM:'PRIVATE'}]}}}, overrides:{'pro-geotech-report':{low:3000,high:4000,note:'Test allowance',excluded:false}} };
const project = {type:'adu',water:'well_existing',wastewater:'septic_existing',new_sqft:750};
const draft = Drafts.snapshot(state,project,'Test draft','Client handles survey');
assert.equal(draft.stage,'early_bid'); assert.equal(draft.approved_revision,null);
assert(!JSON.stringify(draft).includes('PRIVATE'), 'personal record fields are never saved');
Drafts.save(storage,draft);
const loaded=Drafts.list(storage)[0];
assert.deepEqual(loaded.project,project); assert.deepEqual(loaded.overrides,state.overrides);
assert.equal(loaded.screening.layers.wetland.status,'unknown');
const restored = Screen.buildParcel([{geometry:loaded.parcel.geometry}], loaded.parcel);
assert(Math.abs(restored.area_sqft-parcel.area_sqft)<0.001);
assert.equal(Geo.gridAnalyze(restored.shape,[],{targetSamples:100}).totals.clear.pct,100);
Drafts.save(storage,{...draft,title:'Updated draft'}); assert.equal(Drafts.list(storage).length,1);
Drafts.save(storage,{...draft,id:'second',title:'Second bid'}); assert.equal(Drafts.list(storage).length,2);
assert.equal(Drafts.list(storage).find(x=>x.id==='first').title,'Updated draft');
const before=JSON.stringify([...values]);
assert.throws(()=>Drafts.save({...storage,setItem:()=>{throw Error('Storage full');}}, {...draft,title:'Not saved'}),/Storage full/);
assert.equal(JSON.stringify([...values]),before,'quota failure leaves saved bids intact');
values.set('davapprove.bid-drafts.v1','not JSON');
assert.throws(()=>Drafts.save(storage,draft));
assert.equal(values.get('davapprove.bid-drafts.v1'),'not JSON','corrupt storage is never silently overwritten');
console.log('PASS: bid drafts (scope, quotes, independent bids, restored geometry, privacy, corrupt storage and quota errors).');
